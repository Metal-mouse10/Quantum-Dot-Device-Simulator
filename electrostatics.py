if __name__ == "__main__":

    summary = summarize_potential()

    print("Electrostatic model")
    print("===================")

    print(
        f"Potential range: "
        f"{summary['phi_min']:.4f} V → "
        f"{summary['phi_max']:.4f} V"
    )

    print(
        f"Electron energy range: "
        f"{summary['U_min_meV']:.4f} → "
        f"{summary['U_max_meV']:.4f} meV"
    )
